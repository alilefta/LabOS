export const LABOS_ROLE_PERMISSION_BUNDLES = createRolePermissionBundles({
	roles: LABOS_ORGANIZATION_ROLES,
	permissions: LABOS_PERMISSIONS,
	bundles: LABOS_ROLE_PERMISSION_DEFINITIONS,
})

/** Role-only potential capability; resource policy evaluation remains required. */
export function roleBundleHasPermission(
	role: LabOSOrganizationRole,
	permission: LabOSPermission,
) {
	return LABOS_ROLE_PERMISSION_BUNDLES.has(role, permission)
}
